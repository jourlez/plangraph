test('parseFindings: blank lines skipped, errors never echo line content, limits enforced', () => {
  const r = parseFindings('\n{"key":"a","kind":"k","text":"t"}\n\n[1]\n{"key":1,"kind":"k","text":"t"}\nSECRET-TOKEN\n', 'x');
  assert.equal(r.findings.length, 1); assert.deepEqual(r.errors.map((e) => e.split(':').slice(0, 2).join(':')), ['x:4', 'x:5', 'x:6']);
  assert.ok(!r.errors.join('\n').includes('SECRET-TOKEN'));
  const long = parseFindings('x'.repeat((1 << 20) + 1) + '\n', 'big'); assert.equal(long.errors.length, 1); assert.match(long.errors[0], /^big:1: /);
  const many = parseFindings('{"key":"a","kind":"k","text":"t"}\n'.repeat(100001), 'm');
  assert.equal(many.findings.length, 100000); assert.equal(many.errors.length, 1);
});
test('parseFindings accepts sp: task keys up to 120 characters and still rejects unsafe keys', () => {
  const ok = ['sp:2026-11-20-widget-export/3', 'sp:2026-11-20-widget-export', `sp:${'a'.repeat(48)}/${'1'.repeat(24)}`, 'A' + 'b'.repeat(119)];
  const r = parseFindings(ok.map((key) => JSON.stringify({ key, kind: 'k', text: 't' })).join('\n'), 'f');
  assert.deepEqual(r.errors, []); assert.deepEqual(r.findings.map((f) => f.key), ok);
  const bad = ['sp:a/../b', 'sp:a/..', '../T-1', 'T-1\u0001', 'T-<1', 'sp:a/1\n', '/sp:a', 'A' + 'b'.repeat(120), 'sp:a b'];
  const b = parseFindings(bad.map((key) => JSON.stringify({ key, kind: 'k', text: 't' })).join('\n'), 'f');
  assert.equal(b.findings.length, 0); assert.equal(b.errors.length, bad.length); assert.ok(b.errors.every((e) => /invalid key$/.test(e)));
});

