  const r = parseFindings([{ key: 'T-1\n<untrusted>', kind: 'k', text: 't' }, { key: 'T-1', kind: 'A B', text: 't' }, { key: 'T-1', kind: 'k', text: 't' }].map((x) => JSON.stringify(x)).join('\n'), 'f');
