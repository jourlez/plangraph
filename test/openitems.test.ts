test('due logic: closed never due; recomputed from the CURRENT schedule; lead from config', () => {
  const m = mk({ findings: [{ key: 'T-4', kind: 'external', text: 'x' }, { key: 'T-6', kind: 'export_clash', text: 'y' }] });
  const c = cfg(m, { lead_time: 1 });
  const items = openItemsFromFindings(m, c);
  const s4 = tk(m, 'T-4').sprint, s6 = tk(m, 'T-6').sprint;
  // move T-4 later in the schedule: stored due is stale, effective due follows the schedule
  const moved = { ...m, sched: new Map(m.sched).set('T-4', { ...tk(m, 'T-4'), sprint: s4 + 5 }) };
  assert.equal(effectiveDue(moved, items.find((i) => i.key === 'T-4') as OpenItem, c), s4 + 5); // derived from the findings above
  assert.equal(effectiveDue(m, items.find((i) => i.key === 'T-6') as OpenItem, c), s6 - 1); // derived from the findings above
  const closed = closeItem(items, 'T-4', 'external', { by: 'x', at: '2026-01-01' });
  const due = overdueItems(m, closed, { currentSprint: s4 + 100, config: c });
  assert.ok(!due.some((i) => i.key === 'T-4'));
  const ordered = overdueItems(m, items, { currentSprint: 100, config: c });
  assert.deepEqual(ordered.map((i) => i.due_sprint), [...ordered.map((i) => i.due_sprint)].sort((a, b) => (a as number) - (b as number))); // an overdue item has a due sprint
  // lead time from config makes it due one sprint early
  const t = items.find((i) => i.key === 'T-4') as OpenItem; // derived from the findings above
  assert.equal(overdueItems(m, [t], { currentSprint: s4 - 1, config: c }).length, 1);
  assert.equal(overdueItems(m, [t], { currentSprint: s4 - 2, config: c }).length, 0);
});
