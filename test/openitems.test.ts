test('integration contract with ready: blocksReady matches the inline closed-set logic of `ready`', () => {
  // Independent oracle = the code in bin/brain `ready`: closed = Set(status==='done' -> key|kind); a finding blocks unless closed.
  const oracle = (items: OpenItem[], findings: readonly PlanRecord[], key: string) => { const closed = new Set(items.filter((i) => i.status === 'done').map((i) => i.key + '|' + i.kind)); return findings.filter((f) => f.key === key && !closed.has(key + '|' + f.kind)).length > 0; };
  const m = mk(); const d = openItemsFromFindings(m, cfg(m)); const r = rng(5);
  for (let n = 0; n < 50; n++) {
    let reg: OpenItem[] = d; for (const i of d) if (r() < 0.5) reg = closeItem(reg, i.key, i.kind, { by: 'x', at: '2026-01-01' });
    for (const key of ['T-3', 'T-5', 'T-9', 'T-1']) assert.equal(blocksReady(reg, key, { findings: m.findings }), oracle(reg, m.findings, key), key);
  }
  assert.equal(blocksReady(d, 'T-5'), true);
  assert.equal(blocksReady(closeItem(closeItem(d, 'T-5', 'external', { by: 'x', at: 'd' }), 'T-5', 'plan_text', { by: 'x', at: 'd' }), 'T-5'), false);
  assert.equal(blocksReady(closeItem(d, 'T-5', 'external', { by: 'x', at: 'd' }), 'T-5'), true, 'one still open');
  assert.equal(blocksReady(d, 'T-1'), false);
  assert.deepEqual([...closedSet(closeItem(d, 'T-3', 'plan_text', { by: 'x', at: 'd' }))], ['T-3|plan_text']);
  assert.equal(blockingItems(d, 'T-5').length, 2);
  // a finding with no register item (stale register) still blocks, as in `ready`
  assert.equal(blocksReady([], 'T-3', { findings: m.findings }), true);
  // a manual open item blocks too
  assert.equal(blocksReady(registerItem([], { key: 'T-1', kind: 'm', owner: 'o', text: 't' }), 'T-1'), true);
  // status other than 'done' blocks (matches ready: only 'done' closes)
  assert.equal(blocksReady([{ key: 'T-1', kind: 'm', status: 'wontfix' }], 'T-1'), true);
});
