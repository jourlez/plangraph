#!/usr/bin/env node
// Eval runner. It NEVER makes a paid model call by default. Modes:
//   node evals/run.mjs --dry-run                      print the exact commands (claude plugin eval, claude -p); executes nothing
//   node evals/run.mjs --emit-native                  write the native plugin-eval case directories (evals/<case>/, git-ignored)
//   node evals/run.mjs --run --max-cost-usd 25        emit the native cases, then run `claude plugin eval` (PAID); both flags are required
// Selection: --case ID, --kind task|trigger|canary. Tuning: --runs N (1..50), --model M, --judge-model M, --concurrency N (1..8).
// Every `claude plugin eval` flag printed here was checked against `claude plugin eval --help` of Claude Code 2.1.329; --no-publish is always
// passed because the default publishes the HTML report (prompts, transcripts) to claude.ai. See evals/README.md for what is still unverified.
// Exit codes: 0 ok, 2 usage or configuration error (fixed messages, never echoing the offending value).
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { readCapped } from '../lib/jsonl.mjs';
import { writeAtomicSafe } from '../lib/fsafe.mjs';
import { validateCase } from './schema.mjs';

const here = import.meta.dirname;
const root = path.resolve(here, '..');
const MAX_CASE_BYTES = 64 * 1024;
const FLAGS = { bool: ['dry-run', 'emit-native', 'run', 'help'], val: ['case', 'kind', 'runs', 'model', 'judge-model', 'concurrency', 'max-cost-usd'] };
const DEFAULT_MODEL = 'claude-sonnet-5-5'; // from the research doc; pin it so a model rollout is not mistaken for a plugin regression
const DEFAULT_JUDGE = 'claude-haiku-5-5';
const NATIVE_TOOLS = ['Bash(brain *)', 'Bash(jq *)', 'Bash(grep *)', 'Bash(rg *)', 'Bash(node *)'];

class Usage extends Error {}
const usage = (m) => { throw new Usage(m); };

export function parseArgs(argv) {
  const o = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith('--')) usage('unexpected argument');
    const n = a.slice(2);
    if (FLAGS.bool.includes(n)) o[n] = true;
    else if (FLAGS.val.includes(n)) { const v = argv[++i]; if (v === undefined || v.startsWith('--')) usage(`--${n} needs a value`); o[n] = v; }
    else usage('unknown option');
  }
  return o;
}

// Strict numbers: digits only (no NaN, inf, hex, exponent, sign, whitespace), bounded.
export function strictNumber(s, { min, max, int = false, what }) {
  if (typeof s !== 'string' || !(int ? /^\d{1,6}$/ : /^\d{1,6}(?:\.\d{1,4})?$/).test(s)) usage(`${what} must be a plain number`);
  const n = Number(s);
  if (!Number.isFinite(n) || n < min || n > max) usage(`${what} must be between ${min} and ${max}`);
  return n;
}
const modelName = (s, what) => { if (!/^[A-Za-z0-9._-]{1,60}$/.test(s)) usage(`${what} is not a model name`); return s; };

export function loadCases(dir = path.join(here, 'cases')) {
  const out = [];
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json')).sort()) {
    const full = path.join(dir, f);
    let c;
    try { c = JSON.parse(readCapped(full, MAX_CASE_BYTES)); } catch { usage('a case file is unreadable or not JSON'); }
    const e = validateCase(c);
    if (e.length) usage('a case file is invalid; run node --test test/evals-schema.test.mjs');
    if (f !== `${c.id}.json`) usage('a case file name differs from its id');
    out.push(c);
  }
  if (!out.length) usage('no cases found; run node evals/gen.mjs');
  return out;
}

export const sq = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`;
const yq = (s) => `'${String(s).replace(/'/g, "''")}'`;

// ---------------------------------------------------------------- native plugin-eval case directories (generated from the JSON)
export function nativeFiles(c, runs) {
  const f = new Map();
  const tools = ['Read', 'Glob', 'Grep', 'Skill']; // Bash is granted only through --allow-tools on the command line
  f.set(`${c.id}/prompt.md`, `---\nname: ${c.id}\ntags: [${c.tags.join(', ')}]\nruns: ${runs}\nmax_turns: ${c.limits.max_turns}\ntimeout_seconds: ${c.limits.timeout_s}\nallowed_tools: [${tools.join(', ')}]\n---\n\n${c.prompt}\n`);
  f.set(`${c.id}/case.yaml`, `schema_version: "1.1"\nname: ${c.id}\ncontext:\n  scaffold_script: scaffold.sh\n`);
  f.set(`${c.id}/scaffold.sh`, [
    '#!/usr/bin/env bash', '# generated by evals/run.mjs --emit-native from evals/cases/*.json; do not edit', 'set -euo pipefail',
    'case_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"', 'plugin_root="$(cd "$case_dir/../.." && pwd)"',
    'fx="$case_dir/../fixtures/M"', 'mkdir .brain', 'cp "$fx"/*.jsonl "$fx"/config.json "$fx"/format.json .brain/', 'cp "$fx/plan.md" plan.md',
    'git init -q', 'git -c user.name=eval -c user.email=eval@example.invalid add -A', 'git -c user.name=eval -c user.email=eval@example.invalid commit -qm fixture',
    'node "$plugin_root/bin/brain" build >/dev/null', '',
  ].join('\n'));
  for (const g of c.graders) {
    const y = ['type: ' + g.type];
    if (g.type === 'regex') { y.push('target: ' + g.target, 'pattern: ' + yq(g.pattern)); }
    else { y.push('tool: ' + g.tool); if (g.input_match !== undefined) y.push('input_match: ' + yq(g.input_match)); if (g.min !== undefined) y.push('min: ' + g.min); if (g.max !== undefined) y.push('max: ' + g.max); }
    y.push('weight: ' + g.weight, 'arm: ' + g.arm);
    f.set(`${c.id}/graders/${g.id}.md`, `---\n${y.join('\n')}\n---\n`);
  }
  return f;
}

function emitNative(cases, runs, outDir = here) {
  fs.mkdirSync(outDir, { recursive: true });
  for (const c of cases) {
    if (!fs.existsSync(path.join(here, 'fixtures', 'M', 'tickets.jsonl'))) usage('fixtures are missing; run node evals/gen.mjs');
    for (const [p, text] of nativeFiles(c, runs)) {
      const full = path.join(outDir, p);
      fs.mkdirSync(path.dirname(full), { recursive: true });
      writeAtomicSafe(full, text, { root: outDir });
      if (p.endsWith('.sh')) fs.chmodSync(full, 0o755);
    }
  }
  return cases.length;
}

// ---------------------------------------------------------------- command printing
export function commands(cases, o) {
  const model = o.model, judge = o.judge, runs = o.runs, conc = o.concurrency, budget = o.budget;
  const out = [];
  const line = (s = '') => out.push(s);
  line('# Nothing below has been run. `claude plugin eval` flags were checked against Claude Code 2.1.329; the `claude -p` condition commands and `brain` on PATH inside them are partly UNVERIFIED (see evals/README.md). Run from a shell with `claude` installed.');
  line(`PB=${sq(root)}`);
  line();
  line('# 1. regenerate fixtures and cases (deterministic; fails if committed files are out of date)');
  line('node "$PB/evals/gen.mjs" --check');
  line();
  line('# 2. native plugin eval: WITH the plugin versus WITHOUT (delta = WITH - WITHOUT); needs Claude Code >= 2.1.269 and git >= 2.31');
  line('node "$PB/evals/run.mjs" --emit-native' + (o.case ? ` --case ${o.case}` : '') + (o.kind ? ` --kind ${o.kind}` : '') + ` --runs ${runs}`);
  const ev = ['claude', 'plugin', 'eval', '.', '--scaffold', '--trust-plugin', '--no-publish', '--allow-tools', ...NATIVE_TOOLS.map(sq), '--ablation', 'with-without', '--model', model, '--judge-model', judge, '--runs', String(runs), '-j', String(conc), '--threshold', '0.8', '--max-cost-usd', String(budget), '--json', 'evals/results/headline.json'];
  if (o.case) ev.push('--case', o.case);
  line(`( cd "$PB" && mkdir -p evals/results && ${ev.join(' ')} )`);
  line('# NOTE: --allow-tools applies to BOTH arms and every case. Skill-fired graders are reported but not scored in two-arm runs.');
  line();
  line('# 3. one run of one case with plain `claude -p` (condition B = plugin, A = no plugin). Fresh workspace per run; never add --bare to B:');
  line('#    plugin hooks do not run in bare mode (documented, unverified here). `brain` on PATH inside B is also unverified.');
  for (const c of cases) {
    for (const cond of ['B', 'A']) {
      const tools = cond === 'B' ? NATIVE_TOOLS : NATIVE_TOOLS.filter((t) => !t.startsWith('Bash(brain'));
      const cmd = ['claude', '-p', sq(c.prompt), ...(cond === 'B' ? ['--plugin-dir', '"$PB"'] : []), '--model', model, '--max-turns', String(c.limits.max_turns), '--max-budget-usd', String(c.limits.max_usd), '--allowedTools', ...['Read', 'Grep', 'Glob', ...tools].map(sq), '--output-format', 'stream-json', '--verbose', '--no-session-persistence'];
      line(`( ws="$(mktemp -d)" && mkdir -p "$PB/evals/results/runs/${cond}" && cd "$ws" && bash "$PB/evals/${c.id}/scaffold.sh" && ${cmd.join(' ')} > "$PB/evals/results/runs/${cond}/${c.id}.jsonl" )`);
    }
  }
  line();
  const total = cases.reduce((s, c) => s + c.limits.max_usd, 0) * runs * 2;
  line(`# worst-case spend of step 2 if every run hit its per-case cap: ${total.toFixed(2)} USD over ${cases.length} cases x ${runs} runs x 2 arms; --max-cost-usd ${budget} stops the run early (exit 2 on partial)`);
  return out.join('\n') + '\n';
}

function main(argv) {
  const o = parseArgs(argv);
  if (o.help || argv.length === 0) {
    const head = []; for (const l of fs.readFileSync(import.meta.filename, 'utf8').split('\n').slice(1)) { if (!l.startsWith('//')) break; head.push(l.slice(3)); }
    process.stdout.write(head.join('\n') + '\n');
    return 0;
  }
  const modes = ['dry-run', 'emit-native', 'run'].filter((m) => o[m]);
  if (modes.length !== 1) usage('choose exactly one of --dry-run, --emit-native, --run');
  if (o.run && o['max-cost-usd'] === undefined) usage('--run needs --max-cost-usd (paid model calls need an explicit cap)');
  if (!o.run && o['max-cost-usd'] !== undefined && !o['dry-run']) usage('--max-cost-usd only applies to --run or --dry-run');
  const runs = o.runs === undefined ? 3 : strictNumber(o.runs, { min: 1, max: 50, int: true, what: '--runs' });
  const conc = o.concurrency === undefined ? 3 : strictNumber(o.concurrency, { min: 1, max: 8, int: true, what: '--concurrency' });
  const budget = o['max-cost-usd'] === undefined ? 25 : strictNumber(o['max-cost-usd'], { min: 0.01, max: 1000, what: '--max-cost-usd' });
  const model = modelName(o.model ?? DEFAULT_MODEL, '--model'), judge = modelName(o['judge-model'] ?? DEFAULT_JUDGE, '--judge-model');
  let cases = loadCases();
  if (o.kind !== undefined) { if (!['task', 'trigger', 'canary'].includes(o.kind)) usage('--kind must be task, trigger or canary'); cases = cases.filter((c) => c.kind === o.kind); }
  if (o.case !== undefined) { if (!/^[a-z0-9][a-z0-9-]{2,60}$/.test(o.case)) usage('--case is not a case id'); cases = cases.filter((c) => c.id === o.case); }
  if (!cases.length) usage('no case matches the selection');
  const sel = { runs, concurrency: conc, budget, model, judge, case: o.case, kind: o.kind };

  if (o['dry-run']) { process.stdout.write(commands(cases, sel)); return 0; }
  if (o['emit-native']) { const n = emitNative(cases, runs); process.stdout.write(`wrote ${n} native case directories under evals/ (git-ignored)\n`); return 0; }
  // --run: the only path that spends money. Both --run and --max-cost-usd were required above.
  emitNative(cases, runs);
  const args = ['plugin', 'eval', '.', '--scaffold', '--trust-plugin', '--no-publish', '--allow-tools', ...NATIVE_TOOLS, '--ablation', 'with-without', '--model', model, '--judge-model', judge, '--runs', String(runs), '-j', String(conc), '--threshold', '0.8', '--max-cost-usd', String(budget), '--json', 'evals/results/headline.json', ...(o.case ? ['--case', o.case] : [])];
  fs.mkdirSync(path.join(here, 'results'), { recursive: true });
  try { execFileSync('claude', args, { cwd: root, stdio: 'inherit' }); } catch (e) {
    if (e && e.code === 'ENOENT') usage('claude is not installed or not on PATH');
    return typeof e.status === 'number' ? e.status : 1;
  }
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(fs.realpathSync(process.argv[1])).href) {
  try { process.exitCode = main(process.argv.slice(2)); } catch (e) {
    if (e instanceof Usage) { process.stderr.write(`error: ${e.message}\n`); process.exitCode = 2; } else throw e;
  }
}
